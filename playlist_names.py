def suggest_names(genre="", mood="", event="", genre_label="", from_liked=False, count=5):
    """כמה הצעות לשם פלייליסט שמתאים לאווירה שנבחרה, מהמתאים ביותר."""
    energy = MOOD_ENERGY.get(mood)
    names = []
    if event in EVENT_NAMES:
        pools = EVENT_NAMES[event]
        # בלי מצב רוח: השמות הכלליים והאנרגטיים של האירוע
        primary = pools[energy] if energy else pools["any"] + pools["up"]
        names = random.sample(primary, len(primary)) + random.sample(pools["any"], len(pools["any"]))
    elif mood in MOOD_NAMES:
        names = random.sample(MOOD_NAMES[mood], len(MOOD_NAMES[mood]))
    if genre in GENRE_NAMES and not names:
        names = random.sample(GENRE_NAMES[genre], len(GENRE_NAMES[genre]))
    elif genre_label and names:
        # ז'אנר בנוסף לאירוע או למצב רוח: מוסיפים אותו לשם, למשל "יאללה בלאגן · מזרחית"
        names = [f"{name} · {genre_label}" for name in names]
    if not names:
        names = [f"{genre_label} מיקס" if genre_label else "המיקס שלי"]
    if from_liked:
        names = [f"{name} ❤️" for name in names]
    return list(dict.fromkeys(names))[:count]
